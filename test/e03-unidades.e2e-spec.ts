import { randomUUID } from 'crypto';
import { PrismaService } from '../src/prisma/prisma.service';
import { UnidadesService } from '../src/orgaos/unidades.service';
import { ParticipacaoService } from '../src/orgaos/participacao.service';
import { DesativacaoOrgaoService } from '../src/orgaos/desativacao-orgao.service';

const integration = process.env.E00_INTEGRATION === '1' ? describe : describe.skip;
const igreja = 'e0000000-0000-4000-8000-000000000001';
const outra = 'e0000000-0000-4000-8000-000000000002';
const admin = 'e1000000-0000-4000-8000-000000000001';
const pessoa = 'e2000000-0000-4000-8000-000000000001';

integration('E03: instituição de unidade', () => {
  const prisma = new PrismaService();
  const service = new UnidadesService(prisma);
  const gestor = randomUUID();
  const participante = randomUUID();
  const chaveCompetencia = randomUUID(), chaveEncerramento = randomUUID(), chaveFutura = randomUUID(), chaveCancelamento = randomUUID();
  let orgaoId: string | undefined, competenciaId: string | undefined, competenciaFuturaId: string | undefined;
  const input = { nome: 'Unidade de teste', finalidade: 'Finalidade sintética', constituicao: 'DESIGNACAO' as const, data_criacao: '2025-01-01', evidencia: 'Ato sintético', idempotencia: randomUUID() };
  beforeAll(async () => {
    if (process.env.DATABASE_URL !== 'postgresql://provisao_test:provisao_test@127.0.0.1:55439/provisao_test?schema=public') throw new Error('Exige banco descartável E00.');
    await prisma.$connect();
    await prisma.pessoas.create({ data: { id: participante, igreja_id: igreja, nome_completo: 'Participante sintético', data_nascimento: new Date('2010-01-01'), sexo: 'FEMININO' } });
    await prisma.eventos_membresia.create({ data: { igreja_id: igreja, pessoa_id: participante, tipo_evento: 'ADMISSAO', rol: 'NAO_COMUNGANTES', motivacao_evento: 'PROFISSAO_DE_FE', data_evento: new Date('2020-01-01') } });
    await prisma.usuarios.create({ data: { id: gestor, igreja_id: igreja, pessoa_id: pessoa, nome_usuario: 'Gestor sintético', email_login: `${gestor}@example.invalid`, senha_hash: 'inutilizavel', perfil: 'GESTOR' } });
  });
  afterAll(async () => {
    if (orgaoId) {
      const atos = await prisma.ato_orgao.findMany({ where: { orgao_id: orgaoId }, select: { id: true } });
      await prisma.logs_atividades.deleteMany({ where: { registro_id: { in: atos.map(a => a.id) } } });
      await prisma.ato_orgao.deleteMany({ where: { orgao_id: orgaoId } });
      await prisma.membro_orgao.deleteMany({ where: { orgao_id: orgaoId } });
      await prisma.cargo_orgao.deleteMany({ where: { orgao_id: orgaoId } });
      await prisma.contexto_secretaria.deleteMany({ where: { orgao_id: orgaoId } });
      await prisma.versao_orgao.deleteMany({ where: { orgao_id: orgaoId } });
      await prisma.orgao_interno.deleteMany({ where: { id: orgaoId } });
    }
    await prisma.requisicao_institucional.deleteMany({ where: { igreja_id: igreja, idempotencia: { in: [chaveCompetencia, chaveEncerramento, chaveFutura, chaveCancelamento] } } });
    if (competenciaId) await prisma.competencia_unidades.deleteMany({ where: { id: competenciaId } });
    if (competenciaFuturaId) await prisma.competencia_unidades.deleteMany({ where: { id: competenciaFuturaId } });
    await prisma.logs_atividades.deleteMany({ where: { registro_id: { in: [orgaoId ?? '', competenciaId ?? '', competenciaFuturaId ?? ''] } } });
    await prisma.usuarios.deleteMany({ where: { id: gestor } });
    await prisma.eventos_membresia.deleteMany({ where: { pessoa_id: participante } });
    await prisma.pessoas.deleteMany({ where: { id: participante } });
    await prisma.$disconnect();
  });
  it('não presume competência pelo perfil e restringe as igrejas', async () => {
    await expect(service.criar(igreja, gestor, input)).rejects.toThrow();
    const hoje = new Date().toISOString().slice(0, 10);
    const amanha = new Date(new Date(`${hoje}T00:00:00Z`).getTime() + 86400000).toISOString().slice(0, 10);
    const dadosCompetencia = { usuario_id: gestor, inicio: '2024-01-01', fim: amanha, autoridade: 'Autoridade', evidencia: 'Registro', idempotencia: chaveCompetencia };
    await expect(service.registrarCompetencia(outra, admin, dadosCompetencia)).rejects.toThrow();
    await expect(service.registrarCompetencia(igreja, gestor, dadosCompetencia)).rejects.toThrow();
    const competencia = await service.registrarCompetencia(igreja, admin, dadosCompetencia);
    expect(await service.registrarCompetencia(igreja, admin, dadosCompetencia)).toEqual(competencia);
    await expect(prisma.competencia_unidades.delete({ where: { id: competencia.id } })).rejects.toThrow();
    await expect(service.registrarCompetencia(igreja, admin, { ...dadosCompetencia, evidencia: 'Outro registro' })).rejects.toThrow('Chave de repetição');
    competenciaId = competencia.id;
    // O fim é exclusivo: competência válida hoje termina antes do dia informado.
    await prisma.competencia_unidades.update({ where: { id: competencia.id }, data: { fim: new Date(`${hoje}T00:00:00Z`) } });
    await expect(service.criar(igreja, gestor, input)).rejects.toThrow('Competência institucional');
    await prisma.competencia_unidades.update({ where: { id: competencia.id }, data: { fim: new Date(`${amanha}T00:00:00Z`) } });
    const seguinte = await prisma.competencia_unidades.create({ data: { igreja_id: igreja, usuario_id: gestor, pessoa_id: pessoa, registrado_por: admin, inicio: new Date(`${amanha}T00:00:00Z`), autoridade: 'Autoridade', evidencia: 'Sucessão sintética' } });
    await expect(prisma.competencia_unidades.create({ data: { igreja_id: igreja, usuario_id: gestor, pessoa_id: pessoa, registrado_por: admin, inicio: new Date(`${hoje}T00:00:00Z`), autoridade: 'Autoridade', evidencia: 'Sobreposição sintética' } })).rejects.toThrow();
    await prisma.competencia_unidades.delete({ where: { id: seguinte.id } });
    await expect(service.criar(outra, gestor, input)).rejects.toThrow();
    await expect(service.criar(igreja, gestor, { ...input, idempotencia: chaveCompetencia })).rejects.toThrow('Chave de repetição');
    const concorrentes = await Promise.all([service.criar(igreja, gestor, input), service.criar(igreja, gestor, input)]);
    expect(concorrentes[0]).toEqual(concorrentes[1]);
    const orgao = concorrentes[0];
    orgaoId = orgao.id;
    await expect(service.registrarCompetencia(igreja, admin, { ...dadosCompetencia, idempotencia: input.idempotencia })).rejects.toThrow('Chave de repetição');
    expect((await prisma.orgao_interno.findUniqueOrThrow({ where: { id: orgao.id } })).instituidor_id).toBe(pessoa);
    await expect(service.criar(igreja, gestor, { ...input, nome: 'Outro nome' })).rejects.toThrow('Chave de repetição');
    expect(await prisma.cargo_orgao.count({ where: { orgao_id: orgao.id } })).toBe(2);
    expect(await prisma.ato_orgao.count({ where: { orgao_id: orgao.id, tipo: 'INSTITUICAO' } })).toBe(1);
    expect(await prisma.logs_atividades.count({ where: { registro_id: { in: [orgao.id, competencia.id] } } })).toBe(2);
    const participacoes = new ParticipacaoService(prisma);
    const entrada = { pessoa_id: participante, data_efeito: new Date().toISOString().slice(0, 10), evidencia: 'Inscrição sintética', idempotencia: randomUUID() };
    const inscrito = await participacoes.alterar(igreja, gestor, orgao.id, 'INCLUSAO', entrada);
    expect(await participacoes.alterar(igreja, gestor, orgao.id, 'INCLUSAO', entrada)).toEqual(inscrito);
    await expect(participacoes.alterar(igreja, gestor, orgao.id, 'INCLUSAO', { ...entrada, idempotencia: randomUUID() })).rejects.toThrow();
    await expect(participacoes.alterar(igreja, gestor, orgao.id, 'SAIDA', entrada)).rejects.toThrow('Chave de repetição');
    expect(await prisma.membro_orgao.count({ where: { orgao_id: orgao.id, pessoa_id: participante, fim: null } })).toBe(1);
    const desativacoes = new DesativacaoOrgaoService(prisma);
    const desativar = { data_efeito: entrada.data_efeito, motivo: 'Encerramento', autoridade: 'Gestor institucional', evidencia: 'Ato sintético', idempotencia: randomUUID() };
    await expect(desativacoes.desativar(igreja, admin, orgao.id, desativar)).rejects.toThrow();
    const desativado = await desativacoes.desativar(igreja, gestor, orgao.id, desativar);
    const periodo = await prisma.membro_orgao.findUniqueOrThrow({ where: { id: inscrito.membro_id } });
    expect(periodo.fim_ordem).toBeGreaterThan(periodo.inicio_ordem);
    expect(await desativacoes.desativar(igreja, gestor, orgao.id, desativar)).toEqual(desativado);
    expect((await prisma.orgao_interno.findUniqueOrThrow({ where: { id: orgao.id } })).ativo).toBe(false);
    expect((await prisma.membro_orgao.findFirstOrThrow({ where: { orgao_id: orgao.id, pessoa_id: participante } })).fim?.toISOString().slice(0, 10)).toBe(entrada.data_efeito);
    const dadosFim = { data_fim: new Date().toISOString().slice(0, 10), autoridade: 'Autoridade', evidencia: 'Encerramento sintético', idempotencia: chaveEncerramento };
    const encerramento = await service.encerrarCompetencia(igreja, admin, competencia.id, dadosFim);
    const auditoriaFim = await prisma.logs_atividades.findFirstOrThrow({ where: { registro_id: competencia.id, acao: 'ATUALIZACAO' } });
    expect(auditoriaFim.dados_antigos).toMatchObject({ fim: amanha });
    expect(await service.encerrarCompetencia(igreja, admin, competencia.id, dadosFim)).toEqual(encerramento);
    await expect(service.criar(igreja, gestor, input)).rejects.toThrow();
    expect(await prisma.orgao_interno.findUnique({ where: { id: orgao.id } })).not.toBeNull();
    const futura = await service.registrarCompetencia(igreja, admin, { ...dadosCompetencia, inicio: amanha, fim: undefined, idempotencia: chaveFutura });
    competenciaFuturaId = futura.id;
    const cancelamento = { ...dadosFim, idempotencia: chaveCancelamento };
    expect(await service.encerrarCompetencia(igreja, admin, futura.id, cancelamento)).toEqual({ id: futura.id, fim: amanha });
    expect(await service.encerrarCompetencia(igreja, admin, futura.id, cancelamento)).toEqual({ id: futura.id, fim: amanha });
    expect((await prisma.competencia_unidades.findUniqueOrThrow({ where: { id: futura.id } })).fim?.toISOString().slice(0, 10)).toBe(amanha);
    const auditoriaCancelamento = await prisma.logs_atividades.findFirstOrThrow({ where: { registro_id: futura.id, acao: 'ATUALIZACAO' } });
    expect(auditoriaCancelamento.dados_novos).toMatchObject({ fim: amanha, data_ato: hoje });
  });
});
