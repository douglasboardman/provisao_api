import { randomUUID } from 'crypto';
import { PrismaService } from '../src/prisma/prisma.service';
import { DesignacoesService } from '../src/orgaos/designacoes.service';
import { PresidenciaService } from '../src/orgaos/presidencia.service';
import { ComposicaoService } from '../src/orgaos/composicao.service';
import { Test } from '@nestjs/testing';
import { INestApplication } from '@nestjs/common';
import * as request from 'supertest';
import { AppModule } from '../src/app.module';
import { SessionService } from '../src/auth/session.service';

const integration = process.env.E00_INTEGRATION === '1' ? describe : describe.skip;
const igreja = 'e0000000-0000-4000-8000-000000000001', admin = 'e1000000-0000-4000-8000-000000000001';
const date = (s: string) => new Date(`${s}T00:00:00Z`);

integration('E03: designações e dispensa', () => {
  const prisma = new PrismaService(), service = new DesignacoesService(prisma), presidencias = new PresidenciaService(prisma);
  const gestor = randomUUID(), pastor = randomUUID(), membro = randomUUID(), membro2 = randomUUID(), naoComungante = randomUUID(), oficial = randomUUID(), orgao = randomUUID(), cargo = randomUUID(), vice = randomUUID();
  const chavePresidencia = randomUUID(), chaveFim = randomUUID();
  let app: INestApplication, cookieGestor: string;
  const anteriores = [process.env.FEATURE_GOVERNANCA, process.env.FEATURE_ORGAOS, process.env.FEATURE_ORGAOS_GESTAO];
  const hoje = new Date().toISOString().slice(0, 10);
  let presidencia: string;
  beforeAll(async () => {
    if (process.env.DATABASE_URL !== 'postgresql://provisao_test:provisao_test@127.0.0.1:55439/provisao_test?schema=public') throw new Error('Exige banco descartável E00.');
    await prisma.$connect();
    for (const id of [pastor, membro, membro2, naoComungante]) await prisma.pessoas.create({ data: { id, igreja_id: igreja, nome_completo: 'Pessoa sintética', data_nascimento: date('1980-01-01'), sexo: 'MASCULINO' } });
    await prisma.usuarios.create({ data: { id: gestor, igreja_id: igreja, pessoa_id: pastor, nome_usuario: 'Pastor sintético', email_login: `${gestor}@example.invalid`, senha_hash: 'inutilizavel', perfil: 'GESTOR' } });
    process.env.FEATURE_GOVERNANCA = 'true'; process.env.FEATURE_ORGAOS = 'true'; process.env.FEATURE_ORGAOS_GESTAO = 'true';
    app = (await Test.createTestingModule({ imports: [AppModule] }).compile()).createNestApplication();
    await app.init();
    cookieGestor = `provisao_session=${await app.get(SessionService).create(gestor, igreja, 0)}`;
    await prisma.oficial.create({ data: { id: oficial, igreja_id: igreja, pessoa_id: pastor, tipo: 'PRESBITERO_DOCENTE' } });
    await prisma.evento_oficial.create({ data: { igreja_id: igreja, oficial_id: oficial, tipo: 'ORDENACAO', data_efeito: date('2020-01-01'), ordem: 1, autoridade: 'Concílio', evidencia: 'Ato' } });
    await prisma.vinculo_pastoral.create({ data: { igreja_id: igreja, oficial_id: oficial, modalidade: 'Pastor', concilio: 'Concílio', ato: 'Vínculo', data_inicio: date('2020-01-01'), exercicio_institucional: true, evidencia: 'Ato' } });
    for (const [pessoa_id, rol] of [[membro, 'COMUNGANTES'], [membro2, 'COMUNGANTES'], [naoComungante, 'NAO_COMUNGANTES']] as const) await prisma.eventos_membresia.create({ data: { igreja_id: igreja, pessoa_id, tipo_evento: 'ADMISSAO', rol, motivacao_evento: 'PROFISSAO_DE_FE', data_evento: date('2020-01-01') } });
    await prisma.orgao_interno.create({ data: { id: orgao, igreja_id: igreja, tipo: 'UNIDADE_MINISTERIAL', constituicao: 'DESIGNACAO', nome: 'Unidade', finalidade: 'Teste', data_criacao: date('2020-01-01'), criador_id: gestor, instituidor_id: pastor, evidencia_instituicao: 'Ato' } });
    await prisma.cargo_orgao.createMany({ data: [{ id: cargo, igreja_id: igreja, orgao_id: orgao, codigo: 'LIDER', nome: 'Líder' }, { id: vice, igreja_id: igreja, orgao_id: orgao, codigo: 'VICE_LIDER', nome: 'Vice-líder' }] });
    await prisma.ocupacao_cargo.create({ data: { igreja_id: igreja, orgao_id: orgao, cargo_id: vice, pessoa_id: membro, inicio: date('2020-01-01') } });
  });
  afterAll(async () => {
    for (const [i, key] of ['FEATURE_GOVERNANCA', 'FEATURE_ORGAOS', 'FEATURE_ORGAOS_GESTAO'].entries()) { if (anteriores[i] === undefined) delete process.env[key]; else process.env[key] = anteriores[i]; }
    const atos = await prisma.ato_orgao.findMany({ where: { orgao_id: orgao }, select: { id: true } });
    await prisma.logs_atividades.deleteMany({ where: { registro_id: { in: [...atos.map(a => a.id), presidencia ?? ''] } } });
    await prisma.requisicao_institucional.deleteMany({ where: { igreja_id: igreja, idempotencia: { in: [chavePresidencia, chaveFim] } } });
    await prisma.ato_orgao.deleteMany({ where: { orgao_id: orgao } });
    await prisma.ocupacao_cargo.deleteMany({ where: { orgao_id: orgao } });
    await prisma.cargo_orgao.deleteMany({ where: { orgao_id: orgao } });
    await prisma.orgao_interno.deleteMany({ where: { id: orgao } });
    await prisma.presidencia_conselho.deleteMany({ where: { oficial_id: oficial } });
    await prisma.vinculo_pastoral.deleteMany({ where: { oficial_id: oficial } });
    await prisma.evento_oficial.deleteMany({ where: { oficial_id: oficial } });
    await prisma.oficial.deleteMany({ where: { id: oficial } });
    await prisma.eventos_membresia.deleteMany({ where: { pessoa_id: { in: [membro, membro2, naoComungante] } } });
    await prisma.usuarios.deleteMany({ where: { id: gestor } });
    await prisma.pessoas.deleteMany({ where: { id: { in: [pastor, membro, membro2, naoComungante] } } });
    if (app) await app.close();
    await prisma.$disconnect();
  });
  it('exige presidência específica e comungante, e dispensa sem sucessor', async () => {
    const ato = { pessoa_id: membro, data_efeito: hoje, ordem_efeito: 2, evidencia: 'Ato sintético', idempotencia: randomUUID() };
    await expect(service.substituir(igreja, gestor, orgao, cargo, ato)).rejects.toThrow();
    const dadosPresidencia = { oficial_id: oficial, inicio: '2020-01-01', evidencia: 'Presidência conferida', idempotencia: chavePresidencia };
    presidencia = (await presidencias.registrar(igreja, admin, dadosPresidencia)).id;
    expect(await presidencias.registrar(igreja, admin, dadosPresidencia)).toEqual({ id: presidencia });
    await expect(prisma.presidencia_conselho.delete({ where: { id: presidencia } })).rejects.toThrow();
    const composicao = await new ComposicaoService(prisma).consultar(igreja, 'CONSELHO', hoje);
    expect(composicao.membros.some(p => p.pessoa_id === pastor)).toBe(true);
    await expect(service.substituir(igreja, gestor, orgao, cargo, { ...ato, pessoa_id: naoComungante })).rejects.toThrow();
    await expect(service.substituir(igreja, gestor, orgao, cargo, { ...ato, ordem_efeito: 1, idempotencia: randomUUID() })).rejects.toThrow('Acumulação');
    await service.substituir(igreja, gestor, orgao, vice, { ...ato, pessoa_id: null, ordem_efeito: 1, idempotencia: randomUUID() });
    expect(await prisma.ocupacao_cargo.count({ where: { cargo_id: vice, fim: null } })).toBe(0);
    const enviar = () => request(app.getHttpServer()).post(`/orgaos/gestao/${orgao}/cargos/${cargo}/designacoes`).set('Cookie', cookieGestor).set('Origin', 'http://localhost:3001').set('X-Provisao-Request', '1').send(ato);
    const resultados = await Promise.all([enviar(), enviar()]);
    expect(resultados.map(r => r.status)).toEqual([201, 201]);
    expect(resultados[0].body).toEqual(resultados[1].body);
    expect(await prisma.ocupacao_cargo.count({ where: { cargo_id: cargo, fim: null } })).toBe(1);
    await expect(service.substituir(igreja, gestor, orgao, cargo, { ...ato, evidencia: 'Alterado' })).rejects.toThrow('Chave de repetição');
    await expect(service.substituir(igreja, gestor, orgao, cargo, { ...ato, pessoa_id: membro2, idempotencia: randomUUID() })).rejects.toThrow('Ordem');
    await service.substituir(igreja, gestor, orgao, cargo, { ...ato, pessoa_id: membro2, ordem_efeito: 3, idempotencia: randomUUID() });
    const ocupacoes = await prisma.ocupacao_cargo.findMany({ where: { cargo_id: cargo }, orderBy: { inicio_ordem: 'asc' } });
    expect(ocupacoes.map(o => [o.pessoa_id, o.inicio_ordem, o.fim_ordem])).toEqual([[membro, 2, 3], [membro2, 3, null]]);
    const disputa = await Promise.allSettled([1, 2].map(() => service.substituir(igreja, gestor, orgao, cargo, { ...ato, ordem_efeito: 4, idempotencia: randomUUID() })));
    expect(disputa.filter(r => r.status === 'fulfilled')).toHaveLength(1);
    expect(await prisma.ocupacao_cargo.count({ where: { cargo_id: cargo, fim: null } })).toBe(1);
    let liberar!: () => void, avisar!: () => void;
    const bloqueado = new Promise<void>(resolve => { avisar = resolve; });
    const continuar = new Promise<void>(resolve => { liberar = resolve; });
    const encerramentoConcorrente = prisma.$transaction(async tx => {
      await tx.$queryRaw`SELECT id FROM oficial WHERE id = ${oficial} FOR UPDATE`;
      await tx.presidencia_conselho.update({ where: { id: presidencia }, data: { fim: date(hoje) } });
      avisar(); await continuar;
    });
    await bloqueado;
    const tentativaAposEncerramento = service.substituir(igreja, gestor, orgao, vice, { ...ato, ordem_efeito: 5, idempotencia: randomUUID() }).then(() => 'aceito', () => 'recusado');
    await new Promise(resolve => setTimeout(resolve, 100));
    liberar();
    await encerramentoConcorrente;
    expect(await tentativaAposEncerramento).toBe('recusado');
    expect(await prisma.ocupacao_cargo.count({ where: { cargo_id: vice, fim: null } })).toBe(0);
    await prisma.presidencia_conselho.update({ where: { id: presidencia }, data: { fim: null } });
    const dadosFim = { data_efeito: hoje, autoridade: 'Concílio', evidencia: 'Encerramento sintético', idempotencia: chaveFim };
    const encerrado = await presidencias.encerrar(igreja, admin, presidencia, dadosFim);
    expect(await presidencias.encerrar(igreja, admin, presidencia, dadosFim)).toEqual(encerrado);
    expect(await prisma.ocupacao_cargo.count({ where: { cargo_id: cargo, fim: null } })).toBe(1);
  });
});
