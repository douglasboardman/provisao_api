import { randomUUID } from 'crypto';
import { PrismaService } from '../src/prisma/prisma.service';
import { PoliticaUnidadeService } from '../src/orgaos/politica-unidade.service';
import { CargosUnidadeEleitaService } from '../src/orgaos/cargos-unidade-eleita.service';
import { limiteExclusivoPorMeses } from '../src/orgaos/regras-periodos';
import { DesativacaoOrgaoService } from '../src/orgaos/desativacao-orgao.service';
import { OrgaosController } from '../src/orgaos/orgaos.controller';
import { ComposicaoService } from '../src/orgaos/composicao.service';
import { Test } from '@nestjs/testing';
import { INestApplication } from '@nestjs/common';
import * as request from 'supertest';
import { AppModule } from '../src/app.module';
import { SessionService } from '../src/auth/session.service';

const integration = process.env.E00_INTEGRATION === '1' ? describe : describe.skip;
const igreja = 'e0000000-0000-4000-8000-000000000001', outra = 'e0000000-0000-4000-8000-000000000002';
const admin = 'e1000000-0000-4000-8000-000000000001', pessoaOutra = 'e2000000-0000-4000-8000-000000000002';
const data = (s: string) => new Date(`${s}T00:00:00Z`);

integration('E03: diretoria de unidade eleita', () => {
  const prisma = new PrismaService(), politicas = new PoliticaUnidadeService(prisma), cargos = new CargosUnidadeEleitaService(prisma);
  const gestor = randomUUID(), pessoaGestor = randomUUID(), comungante = randomUUID(), naoComungante = randomUUID(), orgao = randomUUID(), cargo = randomUUID();
  let app: INestApplication, cookieGestor: string;
  const anteriores = [process.env.FEATURE_GOVERNANCA, process.env.FEATURE_ORGAOS, process.env.FEATURE_ORGAOS_GESTAO];
  const hoje = new Date().toISOString().slice(0, 10);
  let politicaId = '';
  beforeAll(async () => {
    if (process.env.DATABASE_URL !== 'postgresql://provisao_test:provisao_test@127.0.0.1:55439/provisao_test?schema=public') throw new Error('Exige banco descartável E00.');
    await prisma.$connect();
    for (const id of [pessoaGestor, comungante, naoComungante]) await prisma.pessoas.create({ data: { id, igreja_id: igreja, nome_completo: 'Pessoa sintética', data_nascimento: data('1980-01-01'), sexo: 'FEMININO' } });
    await prisma.usuarios.create({ data: { id: gestor, igreja_id: igreja, pessoa_id: pessoaGestor, nome_usuario: 'Gestora sintética', email_login: `${gestor}@example.invalid`, senha_hash: 'inutilizavel', perfil: 'COMUM' } });
    process.env.FEATURE_GOVERNANCA = 'true'; process.env.FEATURE_ORGAOS = 'true'; process.env.FEATURE_ORGAOS_GESTAO = 'true';
    app = (await Test.createTestingModule({ imports: [AppModule] }).compile()).createNestApplication();
    await app.init();
    cookieGestor = `provisao_session=${await app.get(SessionService).create(gestor, igreja, 0)}`;
    await prisma.competencia_unidades.create({ data: { igreja_id: igreja, usuario_id: gestor, pessoa_id: pessoaGestor, registrado_por: admin, inicio: data('2020-01-01'), autoridade: 'Autoridade', evidencia: 'Ato sintético' } });
    for (const [pessoa_id, rol] of [[comungante, 'COMUNGANTES'], [naoComungante, 'NAO_COMUNGANTES']] as const) await prisma.eventos_membresia.create({ data: { igreja_id: igreja, pessoa_id, tipo_evento: 'ADMISSAO', rol, motivacao_evento: 'PROFISSAO_DE_FE', data_evento: data('2020-01-01') } });
    await prisma.orgao_interno.create({ data: { id: orgao, igreja_id: igreja, tipo: 'UNIDADE_MINISTERIAL', constituicao: 'ELEICAO', nome: 'Unidade sintética', finalidade: 'Teste', data_criacao: data('2020-01-01'), criador_id: gestor, instituidor_id: pessoaGestor, evidencia_instituicao: 'Ato' } });
    await prisma.cargo_orgao.create({ data: { id: cargo, igreja_id: igreja, orgao_id: orgao, codigo: 'PRESIDENTE', nome: 'Presidente' } });
  });
  afterAll(async () => {
    for (const [i, key] of ['FEATURE_GOVERNANCA', 'FEATURE_ORGAOS', 'FEATURE_ORGAOS_GESTAO'].entries()) { if (anteriores[i] === undefined) delete process.env[key]; else process.env[key] = anteriores[i]; }
    const atos = await prisma.ato_orgao.findMany({ where: { orgao_id: orgao }, select: { id: true } });
    await prisma.logs_atividades.deleteMany({ where: { registro_id: { in: atos.map(a => a.id) } } });
    await prisma.ato_orgao.deleteMany({ where: { orgao_id: orgao } });
    await prisma.ocupacao_cargo.deleteMany({ where: { orgao_id: orgao } });
    await prisma.politica_unidade.deleteMany({ where: { orgao_id: orgao } });
    await prisma.cargo_orgao.deleteMany({ where: { orgao_id: orgao } });
    await prisma.orgao_interno.deleteMany({ where: { id: orgao } });
    await prisma.competencia_unidades.deleteMany({ where: { usuario_id: gestor } });
    await prisma.usuarios.deleteMany({ where: { id: gestor } });
    await prisma.eventos_membresia.deleteMany({ where: { pessoa_id: { in: [comungante, naoComungante] } } });
    await prisma.pessoas.deleteMany({ where: { id: { in: [pessoaGestor, comungante, naoComungante] } } });
    if (app) await app.close();
    await prisma.$disconnect();
  });
  it('exige política vigente e comungante, preserva norma e impede concorrência', async () => {
    const regra = { versao: '1', fonte: 'Norma sintética', autoridade: 'Órgão competente', evidencia: 'Ato sintético', inicio: '2020-01-01', fim: '2090-12-31', prazo_maximo_meses: 12, idempotencia: randomUUID() };
    await expect(politicas.registrar(outra, gestor, orgao, regra)).rejects.toThrow();
    politicaId = (await politicas.registrar(igreja, gestor, orgao, regra)).id;
    const controller = app.get(OrgaosController);
    const detalhe = await controller.detalhe({ user: { igreja_id: igreja } }, orgao, hoje);
    expect(detalhe.politicas).toEqual([expect.objectContaining({ id: politicaId, versao: '1', prazo_maximo_meses: 12 })]);
    expect(JSON.stringify(detalhe)).not.toContain('Ato sintético');
    await expect(controller.detalhe({ user: { igreja_id: outra } }, orgao, hoje)).rejects.toThrow();
    expect(await politicas.registrar(igreja, gestor, orgao, regra)).toEqual({ id: politicaId });
    await expect(politicas.registrar(igreja, gestor, orgao, { ...regra, versao: '2' })).rejects.toThrow('Chave de repetição');
    await expect(politicas.registrar(igreja, gestor, orgao, { ...regra, versao: '2', idempotencia: randomUUID() })).rejects.toThrow();
    const limite = limiteExclusivoPorMeses(hoje, 12);
    const ultimo = new Date(data(limite).getTime() - 86400000).toISOString().slice(0, 10);
    const entrada = { pessoa_id: comungante, politica_id: politicaId, data_eleicao: hoje, data_posse: hoje, termino_previsto: ultimo, autoridade: 'Assembleia da unidade', evidencia: 'Resultado sintético', idempotencia: randomUUID() };
    await expect(cargos.registrar(igreja, gestor, orgao, cargo, { ...entrada, termino_previsto: limite })).rejects.toThrow('Prazo');
    await expect(cargos.registrar(igreja, gestor, orgao, cargo, { ...entrada, pessoa_id: naoComungante })).rejects.toThrow('comungante');
    await expect(cargos.registrar(igreja, gestor, orgao, cargo, { ...entrada, pessoa_id: pessoaOutra })).rejects.toThrow();
    const enviar = () => request(app.getHttpServer()).post(`/orgaos/gestao/${orgao}/cargos/${cargo}/eleicao-unidade`).set('Cookie', cookieGestor).set('Origin', 'http://localhost:3001').set('X-Provisao-Request', '1').send(entrada);
    const tentativas = await Promise.all([enviar(), enviar()]);
    expect(tentativas.map(t => t.status)).toEqual([201, 201]);
    expect(tentativas[0].body).toEqual(tentativas[1].body);
    expect(await prisma.ocupacao_cargo.count({ where: { cargo_id: cargo, politica_unidade_id: politicaId } })).toBe(1);
    await expect(cargos.registrar(igreja, gestor, orgao, cargo, { ...entrada, evidencia: 'Evidência alterada' })).rejects.toThrow('Chave de repetição');
    await expect(new DesativacaoOrgaoService(prisma).desativar(igreja, gestor, orgao, { data_efeito: hoje, motivo: 'Extinção', autoridade: 'Gestor', evidencia: 'Ato', idempotencia: randomUUID() })).rejects.toThrow('ocupações');
    await expect(prisma.politica_unidade.update({ where: { id: politicaId }, data: { prazo_maximo_meses: 24 } })).rejects.toThrow();
    const vice = await prisma.cargo_orgao.create({ data: { igreja_id: igreja, orgao_id: orgao, codigo: 'VICE', nome: 'Vice' } });
    const anterior = new Date(data(hoje).getTime() - 86400000);
    const ocupacao = await prisma.ocupacao_cargo.create({ data: { igreja_id: igreja, orgao_id: orgao, cargo_id: vice.id, pessoa_id: naoComungante, inicio: anterior, termino_previsto: data(ultimo), politica_unidade_id: politicaId } });
    const encerramento = { data_efeito: hoje, motivo: 'Renúncia', autoridade: 'Órgão competente', evidencia: 'Ato sintético', idempotencia: randomUUID() };
    await expect(cargos.encerrar(outra, gestor, orgao, ocupacao.id, encerramento)).rejects.toThrow();
    const encerrado = await cargos.encerrar(igreja, gestor, orgao, ocupacao.id, encerramento);
    expect(await cargos.encerrar(igreja, gestor, orgao, ocupacao.id, encerramento)).toEqual(encerrado);
    await expect(cargos.encerrar(igreja, gestor, orgao, ocupacao.id, { ...encerramento, idempotencia: entrada.idempotencia })).rejects.toThrow('Chave de repetição');
    expect((await prisma.ocupacao_cargo.findUniqueOrThrow({ where: { id: ocupacao.id } })).fim?.toISOString().slice(0, 10)).toBe(hoje);
  });
});
